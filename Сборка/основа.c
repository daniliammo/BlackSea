// Запускает make с указанной целью (цель==NULL/"" — полная сборка по умолчанию).
static int запустить_make(const char *имя, const char *цель) {
    char команда[128];
    if (цель && цель[0])
        snprintf(команда, sizeof(команда), "make -j$(nproc) %s", цель);
    else
        snprintf(команда, sizeof(команда), "make -j$(nproc)");

    int статус = выполнить_систему(команда);
    int код = код_возврата(статус);
    if (код != 0) {
        if (статус == -1)
            ошибка("модуль %s: не удалось запустить make (нет /bin/sh?)", имя);
        else
            ошибка("модуль %s: make завершился с кодом %d", имя, код);
        return код ? код : 1;
    }
    return 0;
}

// Собирает программу. cwd уже внутри её каталога (<корень>/Программы/<имя>).
static int собрать_модуль(const char *имя) {
    // Ядро: собираем ТОЛЬКО образ (цель bzImage), без модулей. Модули (=m) в
    // систему не устанавливаются, а полная сборка 5000+ модулей зря тратит
    // время и место на диске. Нужные драйверы вкомпилены в ядро (=y).
    if (strcmp(имя, "Ядро") == 0) {
        // Кладём версионированный конфиг (как для busybox): в дереве ядра его нет
        // (upstream torvalds/linux), а cmdline и фичи (init=/sbin/init, crc32c=y,
        // ext4=y, DRM-драйверы…) живут именно в Сборка/ядро.config. БЕЗ этого
        // копирования ядро собиралось бы со СТАРЫМ .config дерева → cmdline
        // расходится с ожидаемым (была причина «No working init found»).
        char конфиг[PATH_MAX];
        snprintf(конфиг, sizeof(конфиг), "%s/Сборка/ядро.config", КОРЕНЬ);
        if (копировать_файл(конфиг, ".config") != 0)
            return 1;
        // olddefconfig: нормализуем конфиг под текущую версию ядра (дефолты для
        // новых символов), неинтерактивно. Ядерная цель, НЕ oldconfig.
        if (код_возврата(выполнить_систему("make olddefconfig")) != 0) {
            ошибка("Ядро: make olddefconfig не прошёл");
            return 1;
        }
        int код = запустить_make(имя, "bzImage");
        if (код != 0)
            return код;
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/boot/bzImage", КОРЕНЬ);
        if (копировать_файл("arch/x86/boot/bzImage", куда) != 0)
            return 1;
        успех("boot/bzImage");
        return 0;
    }

    // busybox: свой kbuild. Кладём версионированный конфиг (как ядро.config),
    // собираем бинарник и раскладываем applet-symlink'и прямо в rootfs через
    // CONFIG_PREFIX. Конфиг с CONFIG_INSTALL_APPLET_SYMLINKS=y.
    if (strcmp(имя, "busybox") == 0) {
        char конфиг[PATH_MAX];
        snprintf(конфиг, sizeof(конфиг), "%s/Сборка/busybox.config", КОРЕНЬ);
        if (копировать_файл(конфиг, ".config") != 0)
            return 1;
        // .config не должен быть исполняемым — копировать_файл ставит 0755, чинить не нужно
        // (kbuild это не смущает). У busybox цель — oldconfig (НЕ olddefconfig, это
        // ядерная цель); прогоняем неинтерактивно (yes "" → дефолты для новых символов).
        if (код_возврата(выполнить_систему("yes '' | make oldconfig")) != 0) {
            ошибка("busybox: make oldconfig не прошёл");
            return 1;
        }
        int код = запустить_make(имя, NULL);  // собрать бинарник busybox
        if (код != 0)
            return код;
        char команда[PATH_MAX + 64];
        snprintf(команда, sizeof(команда),
                 "make -j$(nproc) CONFIG_PREFIX=\"%s/rootfs\" install", КОРЕНЬ);
        код = код_возврата(выполнить_систему(команда));
        if (код != 0) {
            ошибка("busybox: make install завершился с кодом %d", код);
            return код ? код : 1;
        }
        успех("rootfs (busybox + applet-symlink'и)");
        return 0;
    }

    int код = запустить_make(имя, NULL);  // остальные программы — полная сборка
    if (код != 0)
        return код;

    if (strcmp(имя, "Инициализация") == 0) {
        // Кладём в /sbin/init — ДЕФОЛТНЫЙ путь ядра. Встроенный в ядро cmdline
        // (CONFIG_CMDLINE, см. Сборка/ядро.config) НЕ содержит init=, а UEFI
        // грузит BOOTX64.EFI напрямую (startup.nsh не выполняется). Значит ядро
        // ищет init по умолчанию: /sbin/init первым. Поэтому кастомный init
        // должен лежать именно там — работает без init= в cmdline.
        //
        // busybox `make install` делает /sbin/init СИМЛИНКОМ на busybox. Пишем
        // ПОСЛЕ busybox (scandir+alphasort), а копировать_файл делает remove()
        // перед записью — снимает симлинк и НЕ затирает сам busybox. Итог:
        // /sbin/init = обычный файл кастомного init.
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/rootfs/sbin/init", КОРЕНЬ);
        if (копировать_файл("Собранное/init", куда) != 0)
            return 1;
        успех("rootfs/sbin/init");
        return 0;
    }

    return установить_из_собранное();
}

static int запустить_скрипт(const char *имя_скрипта);  // определён ниже (секция образа)

static int построить_программы(void) {
    char каталог_программ[PATH_MAX];
    snprintf(каталог_программ, sizeof(каталог_программ), "%s/Программы", КОРЕНЬ);

    // scandir + alphasort: детерминированный ОТСОРТИРОВАННЫЙ порядок сборки.
    // Это критично: busybox `make install` (CONFIG_INSTALL_APPLET_SYMLINKS=y)
    // создаёт symlink `sbin/init -> busybox`, а шаг «Инициализация» перезаписывает
    // его кастомным init (тот, что делает `mount -a`). Значит «Инициализация»
    // ДОЛЖНА идти ПОСЛЕ busybox, иначе busybox затрёт кастомный init и система
    // грузится в busybox-init без rcS — не монтируется /proc, всё ломается.
    // Байтово "busybox" (0x62) < "Инициализация" (0xD0…), поэтому сортировка
    // гарантирует нужный порядок. НЕ возвращать readdir (порядок ФС произволен).
    struct dirent **записи = NULL;
    int число = scandir(каталог_программ, &записи, NULL, alphasort);
    if (число < 0) {
        ошибка("не открыть каталог %s: %s", каталог_программ, strerror(errno));
        return 1;
    }

    for (int idx = 0; idx < число; idx++) {
        struct dirent *запись = записи[idx];
        if (прервано)
            break;

        const char *имя = запись->d_name;

        if (strcmp(имя, ".") == 0 || strcmp(имя, "..") == 0)
            continue;
        if (запись->d_type != DT_DIR)
            continue;

        // weston — на meson, а не make. Собираем отдельным скриптом, который
        // конфигурирует/собирает через meson/ninja и раскладывает в rootfs.
        if (strcmp(имя, "weston") == 0) {
            инфо("Собираю: weston (meson)");
            int r = запустить_скрипт("собрать-weston.sh");
            if (прервано)
                break;
            if (r != 0) {
                ошибка("weston не собран (код %d) — продолжаю", r);
                ошибок_счёт++;
                continue;
            }
            успех("готово: weston");
            собрано_счёт++;
            continue;
        }

        // Остальное собираем, только если есть Makefile.
        char путь_каталога[PATH_MAX];
        char путь_makefile[PATH_MAX];
        snprintf(путь_каталога, sizeof(путь_каталога), "%s/%s", каталог_программ, имя);
        snprintf(путь_makefile, sizeof(путь_makefile), "%s/Makefile", путь_каталога);
        if (!файл_существует(путь_makefile)) {
            пропуск("%s (нет Makefile)", имя);
            пропущено_счёт++;
            continue;
        }

        инфо("Собираю: %s", имя);

        if (chdir(путь_каталога) != 0) {
            ошибка("chdir в %s: %s", путь_каталога, strerror(errno));
            ошибок_счёт++;
            continue;
        }

        int результат = собрать_модуль(имя);

        // Прерывание во время сборки этого модуля: не считаем обычной ошибкой,
        // просто выходим из цикла — итог напечатается в main.
        if (прервано)
            break;

        if (результат != 0) {
            // Не прерываем всю сборку из-за одного модуля: считаем ошибку и
            // идём дальше, чтобы собрать остальное и дать полный итог.
            ошибка("модуль %s не собран (код %d) — продолжаю", имя, результат);
            ошибок_счёт++;
            continue;
        }

        успех("готово: %s", имя);
        собрано_счёт++;
    }

    for (int idx = 0; idx < число; idx++)
        free(записи[idx]);
    free(записи);

    if (прервано)
        return 130;               // 128 + SIGINT: сборка прервана
    return ошибок_счёт > 0 ? 1 : 0;  // были ошибки — не идём в создание образа
}

