// ---------------------------------------------------------------------------
// Оркестратор сборки ОС «Чёрное Море».
//
// Живёт в  <корень репозитория>/Сборка  и запускается оттуда (make → run).
// Собирает программы из  <корень>/Программы  и раскладывает артефакты:
//   Ядро            → boot/bzImage
//   Инициализация   → rootfs/sbin/init
//   прочие          → *.so* в rootfs/lib64, остальное в rootfs/bin
// затем создаёт и конвертирует образ скриптами из Сборка/.
//
// ПРАВИЛО сборки: собираем каталог, только если в нём есть Makefile. Не-собираемые
// каталоги (KondaZed, СтандартнаяБиблиотекаКонда, KondaFromClang) пропускаются
// автоматически. Явный чёрный список — только для busybox (свой пайплайн).
// ---------------------------------------------------------------------------

// Абсолютный путь к корню репозитория (родитель каталога Сборка).
static char КОРЕНЬ[PATH_MAX];

// Каталоги, которые НЕ собираем, даже если у них есть Makefile.
static const char *не_собирать[] = {
    "busybox",  // огромный, собирается отдельным пайплайном
};

// ---------------------------------------------------------------------------
// Цветной вывод (ANSI). Цвета включаются, только если поток — терминал и не
// задана переменная NO_COLOR; иначе (файл, пайп, CI) выводится без escape-кодов.
// ---------------------------------------------------------------------------

#define Ц_СБРОС   "\033[0m"
#define Ц_КРАСНЫЙ "\033[1;31m"
#define Ц_ЗЕЛЁНЫЙ "\033[1;32m"
#define Ц_ЖЁЛТЫЙ  "\033[1;33m"
#define Ц_СИНИЙ   "\033[1;34m"

static const char *ц(FILE *поток, const char *код) {
    if (getenv("NO_COLOR") != NULL)
        return "";
    return isatty(fileno(поток)) ? код : "";
}

static void сообщение(FILE *поток, const char *цвет, const char *знак,
                      const char *fmt, va_list ap) {
    fprintf(поток, "%s%s%s ", ц(поток, цвет), знак, ц(поток, Ц_СБРОС));
    vfprintf(поток, fmt, ap);
    fputc('\n', поток);
}

static void инфо(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt);
    сообщение(stdout, Ц_СИНИЙ, "»", fmt, ap);
    va_end(ap);
}
static void успех(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt);
    сообщение(stdout, Ц_ЗЕЛЁНЫЙ, "✓", fmt, ap);
    va_end(ap);
}
static void пропуск(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt);
    сообщение(stdout, Ц_ЖЁЛТЫЙ, "·", fmt, ap);
    va_end(ap);
}
static void ошибка(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt);
    сообщение(stderr, Ц_КРАСНЫЙ, "✗", fmt, ap);
    va_end(ap);
}

// ---------------------------------------------------------------------------
// Разбор статуса system()/wait: превращаем в человекочитаемый код возврата.
// system() возвращает НЕ exit-код, а wait-статус — его нужно декодировать.
// ---------------------------------------------------------------------------

static int код_возврата(int статус) {
    if (статус == -1) return -1;                         // не удалось запустить shell
    if (WIFEXITED(статус)) return WEXITSTATUS(статус);   // обычный выход
    if (WIFSIGNALED(статус)) return 128 + WTERMSIG(статус); // убит сигналом
    return статус;
}

// ---------------------------------------------------------------------------
// Шаги сборки
// ---------------------------------------------------------------------------

typedef int (*шаг_функция)(void);

typedef struct {
    шаг_функция выполнить;
    const char *название;  // для сообщения об ошибке
    const char *успех;     // для сообщения об успехе
} шаг;

static int выполнить_шаги(шаг *шаги, int количество) {
    for (int i = 0; i < количество; i++) {
        int результат = шаги[i].выполнить();
        if (результат != 0) {
            ошибка("Шаг «%s» не выполнен (код %d)", шаги[i].название, результат);
            return результат;
        }
        успех("%s", шаги[i].успех);
    }
    return 0;
}

// ---------------------------------------------------------------------------
// Вспомогательные функции
// ---------------------------------------------------------------------------

static int в_списке(const char *имя, const char **список, size_t количество) {
    for (size_t i = 0; i < количество; i++)
        if (strcmp(имя, список[i]) == 0)
            return 1;
    return 0;
}

static int файл_существует(const char *путь) {
    struct stat st;
    return stat(путь, &st) == 0;
}

// Похоже ли имя на разделяемую библиотеку: содержит ".so" (ловит .so и .so.N).
static int это_библиотека(const char *имя) {
    return strstr(имя, ".so") != NULL;
}

// Копирует файл целиком и выставляет режим 0755; возвращает 0 при успехе.
static int копировать_файл(const char *откуда, const char *куда) {
    struct stat st;
    if (stat(откуда, &st) != 0) {
        ошибка("не найден исходный файл %s: %s", откуда, strerror(errno));
        return 1;
    }

    FILE *src = fopen(откуда, "rb");
    if (!src) {
        ошибка("не открыть исходный файл %s: %s", откуда, strerror(errno));
        return 1;
    }

    FILE *dest = fopen(куда, "wb");
    if (!dest) {
        ошибка("не открыть файл назначения %s: %s", куда, strerror(errno));
        fclose(src);
        return 1;
    }

    int код = 0;
    char *buffer = NULL;

    if (st.st_size > 0) {
        buffer = malloc((size_t)st.st_size);
        if (!buffer) {
            ошибка("не хватило памяти под %ld байт", (long)st.st_size);
            код = 1;
            goto завершить;
        }
        if (fread(buffer, 1, (size_t)st.st_size, src) != (size_t)st.st_size) {
            ошибка("ошибка чтения %s: %s", откуда, strerror(errno));
            код = 1;
            goto завершить;
        }
        if (fwrite(buffer, 1, (size_t)st.st_size, dest) != (size_t)st.st_size) {
            ошибка("ошибка записи %s: %s", куда, strerror(errno));
            код = 1;
            goto завершить;
        }
    }

завершить:
    free(buffer);
    fclose(src);
    fclose(dest);
    // Артефакты — исполняемые файлы и библиотеки; выставляем режим явно.
    if (код == 0 && chmod(куда, 0755) != 0)
        ошибка("не выставить права на %s: %s", куда, strerror(errno));
    return код;
}

