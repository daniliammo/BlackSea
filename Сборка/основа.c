// Копирует всё из Собранное/ в rootfs: *.so* → rootfs/lib64, остальное → rootfs/bin.
// ВАЖНО: библиотеки идут в lib64 — только его (и /usr/lib64) ищет загрузчик.
// Отсутствие Собранное/ — не ошибка (модулю нечего устанавливать).
static int установить_из_собранное(void) {
    DIR *build_dir = opendir("Собранное");
    if (!build_dir)
        return 0;

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(build_dir)) != NULL) {
        if (strcmp(запись->d_name, ".") == 0 || strcmp(запись->d_name, "..") == 0)
            continue;
        if (запись->d_type != DT_REG)
            continue;

        const char *подкаталог = это_библиотека(запись->d_name) ? "lib64" : "bin";

        char путь_откуда[PATH_MAX];
        char путь_куда[PATH_MAX];
        snprintf(путь_откуда, sizeof(путь_откуда), "Собранное/%s", запись->d_name);
        snprintf(путь_куда, sizeof(путь_куда), "%s/rootfs/%s/%s",
                 КОРЕНЬ, подкаталог, запись->d_name);

        if (копировать_файл(путь_откуда, путь_куда) != 0) {
            код = 1;
            break;
        }
        успех("rootfs/%s/%s", подкаталог, запись->d_name);
    }

    closedir(build_dir);
    return код;
}

// ---------------------------------------------------------------------------
// Сборка одной программы
// ---------------------------------------------------------------------------

static int запустить_make(const char *имя) {
    int статус = system("make -j$(nproc)");
    int код = код_возврата(статус);
    if (код != 0) {
        if (статус == -1)
            ошибка("модуль %s: не удалось запустить make (нет /bin/sh?)", имя);
        else
            ошибка("модуль %s: make завершился с кодом %d", имя, код);
        return код ? код : 1;
    }
    return 0;
}

// Собирает программу. cwd уже внутри её каталога (<корень>/Программы/<имя>).
static int собрать_модуль(const char *имя) {
    int код = запустить_make(имя);
    if (код != 0)
        return код;

    if (strcmp(имя, "Инициализация") == 0) {
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/rootfs/sbin/init", КОРЕНЬ);
        if (копировать_файл("Собранное/init", куда) != 0)
            return 1;
        успех("rootfs/sbin/init");
        return 0;
    }

    if (strcmp(имя, "Ядро") == 0) {
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/boot/bzImage", КОРЕНЬ);
        if (копировать_файл("arch/x86/boot/bzImage", куда) != 0)
            return 1;
        успех("boot/bzImage");
        return 0;
    }

    return установить_из_собранное();
}

static int построить_программы(void) {
    char каталог_программ[PATH_MAX];
    snprintf(каталог_программ, sizeof(каталог_программ), "%s/Программы", КОРЕНЬ);

    DIR *программы = opendir(каталог_программ);
    if (программы == NULL) {
        ошибка("не открыть каталог %s: %s", каталог_программ, strerror(errno));
        return 1;
    }

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(программы)) != NULL) {
        const char *имя = запись->d_name;

        if (strcmp(имя, ".") == 0 || strcmp(имя, "..") == 0)
            continue;
        if (запись->d_type != DT_DIR)
            continue;
        if (в_списке(имя, не_собирать, sizeof(не_собирать) / sizeof(не_собирать[0]))) {
            пропуск("%s (своя сборка)", имя);
            continue;
        }

        // Собираем только то, у чего есть Makefile.
        char путь_каталога[PATH_MAX];
        char путь_makefile[PATH_MAX];
        snprintf(путь_каталога, sizeof(путь_каталога), "%s/%s", каталог_программ, имя);
        snprintf(путь_makefile, sizeof(путь_makefile), "%s/Makefile", путь_каталога);
        if (!файл_существует(путь_makefile)) {
            пропуск("%s (нет Makefile)", имя);
            continue;
        }

        инфо("Собираю: %s", имя);

        if (chdir(путь_каталога) != 0) {
            ошибка("chdir в %s: %s", путь_каталога, strerror(errno));
            код = 1;
            break;
        }

        int результат = собрать_модуль(имя);
        if (результат != 0) {
            ошибка("сборка модуля %s прервана (код %d)", имя, результат);
            код = результат;
            break;
        }
        успех("готово: %s", имя);
    }

    closedir(программы);
    return код;
}

// ---------------------------------------------------------------------------
// Образ — вызываем скрипты из Сборка/ (они сами находят корень репозитория).
// ---------------------------------------------------------------------------

static int запустить_скрипт(const char *имя_скрипта) {
    char команда[PATH_MAX + 64];
    snprintf(команда, sizeof(команда), "\"%s/Сборка/%s\"", КОРЕНЬ, имя_скрипта);
    int статус = system(команда);
    int код = код_возврата(статус);
    if (код != 0) {
        if (статус == -1)
            ошибка("не удалось запустить %s", имя_скрипта);
        else
            ошибка("%s завершился с кодом %d", имя_скрипта, код);
    }
    return код;
}

static int создать_образ(void) {
    return запустить_скрипт("создать_образ.sh");
}

static int конвертировать_образ(void) {
    return запустить_скрипт("конвертировать_образ.sh");
}

// ---------------------------------------------------------------------------

int main(void) {
    // Корень репозитория — родитель каталога Сборка (откуда нас запускают).
    if (realpath("..", КОРЕНЬ) == NULL) {
        ошибка("не удалось определить корень репозитория: %s", strerror(errno));
        return 1;
    }
    инфо("Корень репозитория: %s", КОРЕНЬ);

    шаг шаги[] = {
        { построить_программы,  "построение программ", "Программы собраны." },
        { создать_образ,        "создание образа",     "Образ создан." },
        { конвертировать_образ, "конвертация образа",  "Образ сконвертирован." },
    };
    return выполнить_шаги(шаги, sizeof(шаги) / sizeof(шаги[0]));
}
