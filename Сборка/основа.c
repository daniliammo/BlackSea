#define _GNU_SOURCE

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <dirent.h>
#include <limits.h>
#include <sys/stat.h>

// ---------------------------------------------------------------------------
// Оркестратор сборки ОС «Чёрное Море».
//
// Живёт в  <корень репозитория>/Сборка  и запускается оттуда (make → run).
// Собирает программы из  <корень>/Программы  и раскладывает артефакты:
//   Ядро            → boot/bzImage
//   Инициализация   → rootfs/sbin/init
//   прочие          → *.so* в rootfs/lib64, остальное в rootfs/bin
// затем создаёт и конвертирует образ.
//
// ПРАВИЛО сборки: собираем каталог, только если в нём есть Makefile. Поэтому
// не-собираемые каталоги (KondaZed, СтандартнаяБиблиотекаКонда, KondaFromClang)
// пропускаются автоматически — их не нужно перечислять. Явный чёрный список —
// только для того, у чего Makefile есть, но своя сборка (busybox).
// ---------------------------------------------------------------------------

// Абсолютный путь к корню репозитория (родитель каталога Сборка).
static char КОРЕНЬ[PATH_MAX];

// Каталоги, которые НЕ собираем, даже если у них есть Makefile.
static const char *не_собирать[] = {
    "busybox",  // огромный, собирается отдельным пайплайном
};

// ---------------------------------------------------------------------------
// Шаги сборки
// ---------------------------------------------------------------------------

typedef int (*шаг_функция)(void);

typedef struct {
    шаг_функция выполнить;
    const char *ошибка;
    const char *успех;
} шаг;

static int выполнить_шаги(шаг *шаги, int количество) {
    for (int i = 0; i < количество; i++) {
        int результат = шаги[i].выполнить();
        if (результат != 0) {
            printf("Ошибка при %s, код: %i\n", шаги[i].ошибка, результат);
            return результат;
        }
        printf("%s\n", шаги[i].успех);
    }
    return 0;
}

// ---------------------------------------------------------------------------
// Вспомогательные функции
// ---------------------------------------------------------------------------

// Проверяет, входит ли имя в список строк.
static int в_списке(const char *имя, const char **список, size_t количество) {
    for (size_t i = 0; i < количество; i++)
        if (strcmp(имя, список[i]) == 0)
            return 1;
    return 0;
}

// Существует ли файл по пути.
static int файл_существует(const char *путь) {
    struct stat st;
    return stat(путь, &st) == 0;
}

// Похоже ли имя на разделяемую библиотеку: содержит ".so" (ловит .so и .so.N).
static int это_библиотека(const char *имя) {
    return strstr(имя, ".so") != NULL;
}

// Копирует файл целиком и выставляет режим 0755; возвращает 0 при успехе.
static int копировать_файл(const char *откуда, const char *куда) {
    struct stat st;
    if (stat(откуда, &st) != 0) {
        fprintf(stderr, "Не найден исходный файл %s: ", откуда);
        perror(NULL);
        return 1;
    }

    FILE *src = fopen(откуда, "rb");
    if (!src) {
        perror("Ошибка открытия исходного файла");
        return 1;
    }

    FILE *dest = fopen(куда, "wb");
    if (!dest) {
        fprintf(stderr, "Ошибка открытия файла назначения %s: ", куда);
        perror(NULL);
        fclose(src);
        return 1;
    }

    int код = 0;
    char *buffer = NULL;

    if (st.st_size > 0) {
        buffer = malloc((size_t)st.st_size);
        if (!buffer) {
            perror("Ошибка выделения памяти");
            код = 1;
            goto завершить;
        }

        if (fread(buffer, 1, (size_t)st.st_size, src) != (size_t)st.st_size) {
            perror("Ошибка чтения файла");
            код = 1;
            goto завершить;
        }

        if (fwrite(buffer, 1, (size_t)st.st_size, dest) != (size_t)st.st_size) {
            perror("Ошибка записи файла");
            код = 1;
            goto завершить;
        }
    }

завершить:
    free(buffer);
    fclose(src);
    fclose(dest);
    // Артефакты — исполняемые файлы и библиотеки; выставляем режим явно,
    // чтобы не зависеть от прежних прав файла назначения.
    if (код == 0)
        chmod(куда, 0755);
    return код;
}

// ---------------------------------------------------------------------------
// Установка артефактов
// ---------------------------------------------------------------------------

// Копирует всё из Собранное/ в rootfs: *.so* → rootfs/lib64, остальное → rootfs/bin.
// ВАЖНО: библиотеки идут в lib64 — только его (и /usr/lib64) ищет загрузчик
// дистрибутива; /lib в путях поиска нет. Отсутствие Собранное/ — не ошибка.
static int установить_из_собранное(void) {
    DIR *build_dir = opendir("Собранное");
    if (!build_dir)
        return 0;

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(build_dir)) != NULL) {
        if (strcmp(запись->d_name, ".") == 0 || strcmp(запись->d_name, "..") == 0)
            continue;
        if (запись->d_type != DT_REG)
            continue;

        const char *подкаталог = это_библиотека(запись->d_name) ? "lib64" : "bin";

        char путь_откуда[PATH_MAX];
        char путь_куда[PATH_MAX];
        snprintf(путь_откуда, sizeof(путь_откуда), "Собранное/%s", запись->d_name);
        snprintf(путь_куда, sizeof(путь_куда), "%s/rootfs/%s/%s",
                 КОРЕНЬ, подкаталог, запись->d_name);

        printf("Копирую %s → rootfs/%s/%s\n", путь_откуда, подкаталог, запись->d_name);
        if (копировать_файл(путь_откуда, путь_куда) != 0) {
            код = 1;
            break;
        }
    }

    closedir(build_dir);
    return код;
}

// ---------------------------------------------------------------------------
// Сборка одной программы
// ---------------------------------------------------------------------------

static int запустить_make(void) {
    if (system("make -j$(nproc)") != 0) {
        fprintf(stderr, "make не вернул код 0\n");
        return 1;
    }
    return 0;
}

// Собирает программу. cwd уже внутри её каталога (<корень>/Программы/<имя>).
static int собрать_модуль(const char *имя) {
    if (запустить_make() != 0)
        return 1;

    if (strcmp(имя, "Инициализация") == 0) {
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/rootfs/sbin/init", КОРЕНЬ);
        return копировать_файл("Собранное/init", куда);
    }

    if (strcmp(имя, "Ядро") == 0) {
        char куда[PATH_MAX];
        snprintf(куда, sizeof(куда), "%s/boot/bzImage", КОРЕНЬ);
        return копировать_файл("arch/x86_64/boot/bzImage", куда);
    }

    return установить_из_собранное();
}

static int построить_программы(void) {
    char каталог_программ[PATH_MAX];
    snprintf(каталог_программ, sizeof(каталог_программ), "%s/Программы", КОРЕНЬ);

    DIR *программы = opendir(каталог_программ);
    if (программы == NULL) {
        perror("Ошибка открытия каталога Программы");
        return 1;
    }

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(программы)) != NULL) {
        const char *имя = запись->d_name;

        if (strcmp(имя, ".") == 0 || strcmp(имя, "..") == 0)
            continue;
        if (запись->d_type != DT_DIR)
            continue;
        if (в_списке(имя, не_собирать, sizeof(не_собирать) / sizeof(не_собирать[0]))) {
            printf("Пропускаю (своя сборка): %s\n", имя);
            continue;
        }

        // Собираем только то, у чего есть Makefile. Прочее (расширения
        // редактора, библиотеки-исходники) пропускаем автоматически.
        char путь_каталога[PATH_MAX];
        char путь_makefile[PATH_MAX];
        snprintf(путь_каталога, sizeof(путь_каталога), "%s/%s", каталог_программ, имя);
        snprintf(путь_makefile, sizeof(путь_makefile), "%s/Makefile", путь_каталога);
        if (!файл_существует(путь_makefile)) {
            printf("Пропускаю (нет Makefile): %s\n", имя);
            continue;
        }

        printf("Работаю над: %s\n", имя);

        if (chdir(путь_каталога) != 0) {
            perror("chdir в модуль");
            код = 1;
            break;
        }

        int результат = собрать_модуль(имя);

        if (результат != 0) {
            fprintf(stderr, "Сборка модуля %s завершилась с ошибкой\n", имя);
            код = результат;
            break;
        }

        printf("Завершено успешно: %s\n", имя);
    }

    closedir(программы);
    return код;
}

// ---------------------------------------------------------------------------
// Образ
// ---------------------------------------------------------------------------

static int создать_образ(void) {
    if (chdir(КОРЕНЬ) != 0) {
        perror("chdir в корень репозитория");
        return 1;
    }
    return system("./создать_образ.sh");
}

static int конвертировать_образ(void) {
    if (chdir(КОРЕНЬ) != 0) {
        perror("chdir в корень репозитория");
        return 1;
    }
    return system("./конвертировать_образ.sh");
}

// ---------------------------------------------------------------------------

int main(void) {
    // Корень репозитория — родитель каталога Сборка (откуда нас запускают).
    if (realpath("..", КОРЕНЬ) == NULL) {
        perror("Не удалось определить корень репозитория");
        return 1;
    }
    printf("Корень репозитория: %s\n", КОРЕНЬ);

    шаг шаги[] = {
        { построить_программы, "построении программ", "Построение программ закончилось успешно!" },
        { создать_образ,       "создании образа",     "Создание образа закончилось успешно!" },
        { конвертировать_образ,"конвертации образа",  "Конвертация образа закончилась успешно!" },
    };
    return выполнить_шаги(шаги, sizeof(шаги) / sizeof(шаги[0]));
}
