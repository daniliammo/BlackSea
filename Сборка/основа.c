// Образ — вызываем скрипты из Сборка/ (они сами находят корень репозитория).
// ---------------------------------------------------------------------------

static int запустить_скрипт(const char *имя_скрипта) {
    char команда[PATH_MAX + 64];
    snprintf(команда, sizeof(команда), "\"%s/Сборка/%s\"", КОРЕНЬ, имя_скрипта);
    int статус = выполнить_систему(команда);
    int код = код_возврата(статус);
    if (код != 0) {
        if (статус == -1)
            ошибка("не удалось запустить %s", имя_скрипта);
        else
            ошибка("%s завершился с кодом %d", имя_скрипта, код);
    }
    return код;
}

static int создать_образ(void) {
    return запустить_скрипт("создать_образ.sh");
}

static int конвертировать_образ(void) {
    return запустить_скрипт("конвертировать_образ.sh");
}

// ---------------------------------------------------------------------------

int main(void) {
    // Единый упорядоченный поток вывода: и наши сообщения, и ВЕСЬ вывод дочерних
    // процессов (make/meson/ninja/gcc, под-скрипты образа) — в ОДНО место,
    // видимое целиком и в терминале, и в логе CI. Почему лог рвался, когда stdout
    // это pipe (CI), а не терминал:
    //   1) glibc делает pipe-stdout ПОЛНОСТЬЮ буферизованным → наши инфо/успех
    //      висят в буфере и вываливаются пачкой в самом конце, а stderr (всегда
    //      небуферизован) и вывод детей идут в реальном времени → «Собираю: X»
    //      отрывается от ошибки X, читать лог невозможно;
    //   2) stdout и stderr — РАЗНЫЕ дескрипторы, на CI их сливают по времени
    //      прихода → перемешивание усиливается.
    // Лечим оба разом, у истока: (а) построчная буферизация stdout — строки
    // уходят сразу и по порядку даже в pipe; (б) dup2(stdout→stderr) — физически
    // ОДИН поток на уровне дескриптора, который наследуют ВСЕ потомки, поэтому
    // НИГДЕ (ни в CI-yaml, ни в под-скриптах) не нужно дописывать 2>&1 / 2>log.txt:
    // и наши ошибки, и stderr make/meson/ninja идут туда же, что и остальной вывод.
    // Обязательно ДО первого вывода.
    setvbuf(stdout, NULL, _IOLBF, 0);
    if (dup2(STDOUT_FILENO, STDERR_FILENO) == -1)
        perror("dup2(stdout->stderr)");  // не фатально: останемся с раздельными потоками

    // Корень репозитория — родитель каталога Сборка (откуда нас запускают).
    if (realpath("..", КОРЕНЬ) == NULL) {
        ошибка("не удалось определить корень репозитория: %s", strerror(errno));
        return 1;
    }
    инфо("Корень репозитория: %s", КОРЕНЬ);

    // Аккуратная обработка Ctrl-C / kill: без SA_RESTART, чтобы прерванные
    // системные вызовы возвращали EINTR, а не перезапускались.
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = обработчик_прерывания;
    sigemptyset(&sa.sa_mask);
    sa.sa_flags = 0;
    sigaction(SIGINT,  &sa, NULL);
    sigaction(SIGTERM, &sa, NULL);

    шаг шаги[] = {
        { построить_программы,  "построение программ", "Программы собраны." },
        { создать_образ,        "создание образа",     "Образ создан." },
        { конвертировать_образ, "конвертация образа",  "Образ сконвертирован." },
    };
    int код = выполнить_шаги(шаги, sizeof(шаги) / sizeof(шаги[0]));

    // Итог по программам печатаем всегда: и при успехе, и при ошибке/прерывании.
    напечатать_итог();
    return код;
}
