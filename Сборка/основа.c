static int файл_существует(const char *путь) {
    struct stat st;
    return stat(путь, &st) == 0;
}

// Похоже ли имя на разделяемую библиотеку: содержит ".so" (ловит .so и .so.N).
static int это_библиотека(const char *имя) {
    return strstr(имя, ".so") != NULL;
}

// Копирует файл целиком и выставляет режим 0755; возвращает 0 при успехе.
static int копировать_файл(const char *откуда, const char *куда) {
    struct stat st;
    if (stat(откуда, &st) != 0) {
        ошибка("не найден исходный файл %s: %s", откуда, strerror(errno));
        return 1;
    }

    FILE *src = fopen(откуда, "rb");
    if (!src) {
        ошибка("не открыть исходный файл %s: %s", откуда, strerror(errno));
        return 1;
    }

    // Снять назначение перед записью. Если куда — СИМЛИНК (напр. busybox делает
    // sbin/init → busybox), fopen("wb") пишет ПО симлинку и затирает цель.
    // remove() удаляет сам симлинк/файл, дальше создаём свежий обычный файл.
    remove(куда);

    FILE *dest = fopen(куда, "wb");
    if (!dest) {
        ошибка("не открыть файл назначения %s: %s", куда, strerror(errno));
        fclose(src);
        return 1;
    }

    int код = 0;
    char *buffer = NULL;

    if (st.st_size > 0) {
        buffer = malloc((size_t)st.st_size);
        if (!buffer) {
            ошибка("не хватило памяти под %ld байт", (long)st.st_size);
            код = 1;
            goto завершить;
        }
        if (fread(buffer, 1, (size_t)st.st_size, src) != (size_t)st.st_size) {
            ошибка("ошибка чтения %s: %s", откуда, strerror(errno));
            код = 1;
            goto завершить;
        }
        if (fwrite(buffer, 1, (size_t)st.st_size, dest) != (size_t)st.st_size) {
            ошибка("ошибка записи %s: %s", куда, strerror(errno));
            код = 1;
            goto завершить;
        }
    }

завершить:
    free(buffer);
    fclose(src);
    fclose(dest);
    // Артефакты — исполняемые файлы и библиотеки; выставляем режим явно.
    if (код == 0 && chmod(куда, 0755) != 0)
        ошибка("не выставить права на %s: %s", куда, strerror(errno));
    return код;
}

