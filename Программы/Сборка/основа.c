static int запустить_make(void) {
    if (system("make -j$(nproc)") != 0) {
        fprintf(stderr, "make не вернул код 0\n");
        return 1;
    }
    return 0;
}

// Копирует все файлы из Собранное/ в rootfs: *.so → rootfs/lib, остальное → rootfs/bin.
// Отсутствие Собранное/ не считается ошибкой (модулю нечего устанавливать).
static int установить_из_собранное(void) {
    DIR *build_dir = opendir("Собранное/");
    if (!build_dir)
        return 0;

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(build_dir)) != NULL) {
        if (strcmp(запись->d_name, ".") == 0 || strcmp(запись->d_name, "..") == 0)
            continue;
        if (запись->d_type != DT_REG)
            continue;

        const char *подкаталог = заканчивается_на(запись->d_name, ".so") ? "lib" : "bin";

        char каталог_куда[PATH_MAX];
        char путь_откуда[PATH_MAX];
        char путь_куда[PATH_MAX];
        snprintf(каталог_куда, sizeof(каталог_куда), "../../rootfs/%s", подкаталог);
        snprintf(путь_откуда, sizeof(путь_откуда), "Собранное/%s", запись->d_name);
        snprintf(путь_куда, sizeof(путь_куда), "%s/%s", каталог_куда, запись->d_name);

        mkdir(каталог_куда, 0755);  // на случай отсутствия rootfs/lib; ошибку игнорируем

        printf("Копирую %s → %s\n", путь_откуда, путь_куда);
        if (копировать_файл(путь_откуда, путь_куда) != 0) {
            код = 1;
            break;
        }
    }

    closedir(build_dir);
    return код;
}

// Собирает один модуль. Предполагается, что cwd уже внутри его директории.
static int собрать_модуль(const char *имя) {
    if (запустить_make() != 0)
        return 1;

    if (strcmp(имя, "Инициализация") == 0)
        return копировать_файл("Собранное/init", "../../rootfs/sbin/init");

    if (strcmp(имя, "Ядро") == 0)
        return копировать_файл("arch/x86_64/boot/bzImage", "../../boot/bzImage");

    return установить_из_собранное();
}

static int построить_программы(void) {
    char база[PATH_MAX];  // директория Сборка — точка возврата
    if (getcwd(база, sizeof(база)) == NULL) {
        perror("getcwd");
        return 1;
    }

    DIR *программы = opendir("..");  // Программы/ — родитель Сборка
    if (программы == NULL) {
        perror("Ошибка открытия директории Программы");
        return 1;
    }

    int код = 0;
    struct dirent *запись;
    while ((запись = readdir(программы)) != NULL) {
        const char *имя = запись->d_name;

        if (strcmp(имя, ".") == 0 || strcmp(имя, "..") == 0)
            continue;
        if (запись->d_type != DT_DIR)
            continue;
        if (в_списке(имя, игнорируемые, sizeof(игнорируемые) / sizeof(игнорируемые[0]))) {
            printf("Пропускаю: %s\n", имя);
            continue;
        }

        printf("Работаю над: %s\n", имя);

        // Переходим в Программы/<имя>, всегда отталкиваясь от известной базы.
        if (chdir(база) != 0 || chdir("..") != 0 || chdir(имя) != 0) {
            perror("chdir в модуль");
            код = 1;
            break;
        }

        int результат = собрать_модуль(имя);

        if (chdir(база) != 0) {  // возвращаемся, что бы ни случилось
            perror("chdir обратно");
            код = 1;
            break;
        }

        if (результат != 0) {
            fprintf(stderr, "Сборка модуля %s завершилась с ошибкой\n", имя);
            код = результат;
            break;
        }

        printf("Завершено успешно: %s\n", имя);
    }

    closedir(программы);
    return код;
}

