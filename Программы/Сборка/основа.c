// Директории в Программы/, которые сборщик не трогает.
static const char *игнорируемые[] = {
    "Сборка",          // сам сборщик
    "busybox",         // собирается отдельно
    "KondaFromClang",  // игнорируется
    "СтандартнаяБиблиотекаКонда"
};

// ---------------------------------------------------------------------------
// Шаги сборки
// ---------------------------------------------------------------------------

typedef int (*шаг_функция)(void);

typedef struct {
    шаг_функция выполнить;
    const char *ошибка;
    const char *успех;
} шаг;

static int выполнить_шаги(шаг *шаги, int количество) {
    for (int i = 0; i < количество; i++) {
        int результат = шаги[i].выполнить();
        if (результат != 0) {
            printf("Ошибка при %s, код: %i\n", шаги[i].ошибка, результат);
            return результат;
        }
        printf("%s\n", шаги[i].успех);
    }
    return 0;
}

